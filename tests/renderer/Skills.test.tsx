import { act, cleanup, fireEvent, render, screen, waitFor, within } from '@testing-library/react';
import { afterEach, beforeEach, expect, it, vi } from 'vitest';
import type { VideoSkillDetail } from '@shared/schema/skills';
import { Skills, SaveSkillDialog } from '../../src/renderer/pages/Skills';
import { VideoTypePicker } from '../../src/renderer/components/VideoTypePicker';
import { useAssistant } from '../../src/renderer/editor/assistantStore';
import { useNavigation } from '../../src/renderer/state/navigation';
import { defaultReply, session } from './fixtures';
const mocks = vi.hoisted(() => ({ invoke: vi.fn(), listeners: new Map<string, (value: unknown) => void>() }));
vi.mock('../../src/renderer/lib/api', () => ({ api: { invoke: mocks.invoke, on: (event: string, listener: (value: unknown) => void) => { mocks.listeners.set(event, listener); return () => mocks.listeners.delete(event); } } }));
const skill = (id: string, source: 'builtin' | 'user'): VideoSkillDetail => ({ id, name: id === 'explainer' ? 'YouTube explainer' : 'My teaser', source, description: 'Reusable structure and style', instructions: 'Use a title, then footage.', compositions: [], updatedAt: '2026-11-08T00:00:00.000Z' });
let skills: VideoSkillDetail[];
beforeEach(() => {
  skills = [skill('explainer', 'builtin'), skill('teaser', 'user')]; mocks.invoke.mockReset(); mocks.listeners.clear();
  mocks.invoke.mockImplementation(async (channel: string, request: { id?: string }) => channel === 'skills.list' ? skills : channel === 'skills.get' ? skills.find((s) => s.id === request.id) : defaultReply(channel));
  useNavigation.setState({ project: session, destination: 'skills' });
  useAssistant.setState({ sessionId: 'agent1', status: 'idle', skillId: null, messages: [], tools: [], permissions: [], questions: [], answeredQuestionIds: [], savedSkill: null, sending: false, error: null, draft: '' });
  HTMLDialogElement.prototype.showModal = function () { this.setAttribute('open', ''); };
  HTMLDialogElement.prototype.close = function () { this.removeAttribute('open'); };
});
afterEach(cleanup);
it('offers editing only for user skills, updates live and selects a type without generating', async () => {
  render(<Skills />); const builtin = (await screen.findByText('YouTube explainer')).closest('article')!;
  expect(within(builtin).queryByRole('button', { name: 'Edit' })).toBeNull(); expect(within(builtin).queryByRole('button', { name: 'Delete' })).toBeNull();
  act(() => mocks.listeners.get('skills.changed')?.([...skills, { ...skill('new', 'user'), name: 'New skill' }]));
  expect(screen.getByText('New skill')).toBeTruthy();
  fireEvent.click(within(builtin).getByRole('button', { name: 'Use in project' }));
  expect(useAssistant.getState().skillId).toBe('explainer'); expect(useNavigation.getState().destination).toBe('project');
  expect(mocks.invoke.mock.calls.some(([channel]) => channel === 'agent.send')).toBe(false);
});
it('retains an edit on save failure and requires confirmation before deleting', async () => {
  render(<Skills />); fireEvent.click(await screen.findByRole('button', { name: 'Edit' }));
  const dialog = await screen.findByRole('dialog', { name: 'Edit skill' });
  fireEvent.change(within(dialog).getByLabelText('Name'), { target: { value: 'Updated teaser' } });
  mocks.invoke.mockImplementation(async (channel: string) => { if (channel === 'skills.save') throw new Error('Could not save skill.'); return skills; });
  fireEvent.click(within(dialog).getByRole('button', { name: 'Save changes' }));
  await within(dialog).findByText('Could not save skill.'); expect((within(dialog).getByLabelText('Name') as HTMLInputElement).value).toBe('Updated teaser');
  fireEvent.click(within(dialog).getByRole('button', { name: 'Cancel' }));
  fireEvent.click(screen.getByRole('button', { name: 'Delete' }));
  const confirmation = screen.getByRole('dialog', { name: 'Delete My teaser?' });
  expect(mocks.invoke.mock.calls.some(([channel]) => channel === 'skills.delete')).toBe(false);
  expect(within(confirmation).getByText(/Projects already made/)).toBeTruthy();
  fireEvent.click(within(confirmation).getByRole('button', { name: 'Delete skill' }));
  await waitFor(() => expect(mocks.invoke).toHaveBeenCalledWith('skills.delete', { id: 'teaser' }));
});
it('filters picker rows, supports keyboard selection, sends the type with the next message and removes it', async () => {
  render(<VideoTypePicker />); fireEvent.click(screen.getByRole('button', { name: 'Video type' }));
  await screen.findByRole('button', { name: /YouTube explainer/ });
  fireEvent.change(screen.getByLabelText('Search video types'), { target: { value: 'not-found' } }); expect(screen.getByText('No matching video types.')).toBeTruthy();
  fireEvent.change(screen.getByLabelText('Search video types'), { target: { value: 'teaser' } });
  const row = screen.getByRole('button', { name: /My teaser/ }); row.focus(); fireEvent.keyDown(row, { key: 'ArrowDown' }); expect(document.activeElement).toBe(row); fireEvent.click(row);
  expect(screen.queryByRole('dialog')).toBeNull(); expect(useAssistant.getState().skillId).toBe('teaser');
  expect(await useAssistant.getState().send('Make a product video')).toBe(true);
  expect(mocks.invoke).toHaveBeenCalledWith('agent.send', expect.objectContaining({ skillId: 'teaser' }));
  fireEvent.click(screen.getByRole('button', { name: 'Remove video type' })); expect(useAssistant.getState().skillId).toBeNull();
});
it('saves the current edit only through chat, never a direct skills.save call', async () => {
  const close = vi.fn(); render(<SaveSkillDialog onClose={close} />);
  fireEvent.change(screen.getByLabelText('Name'), { target: { value: 'My style' } });
  fireEvent.change(screen.getByLabelText('Description'), { target: { value: 'Short title and footage' } });
  fireEvent.click(screen.getByRole('button', { name: 'Continue in chat' }));
  await waitFor(() => expect(close).toHaveBeenCalledOnce());
  expect(mocks.invoke).toHaveBeenCalledWith('agent.send', expect.objectContaining({ text: expect.stringContaining('via skill_save') }));
  expect(mocks.invoke.mock.calls.some(([channel]) => channel === 'skills.save')).toBe(false); expect(useAssistant.getState().savedSkill).toBeNull();
});
it('asks for a project when no project is open without sending a request', async () => {
  useNavigation.setState({ project: null }); render(<Skills />);
  expect((screen.getByRole('button', { name: 'Save this edit as a skill' }) as HTMLButtonElement).disabled).toBe(true);
  fireEvent.click((await screen.findAllByRole('button', { name: 'Use in project' }))[0]!);
  expect(screen.getByRole('dialog', { name: 'Choose a project' })).toBeTruthy(); expect(mocks.invoke.mock.calls.some(([channel]) => channel === 'agent.send')).toBe(false);
});
